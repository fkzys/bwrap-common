#!/usr/bin/env bash
# bwrap-common: seccomp filter support.
# Loaded by bwrap-common.sh; do not source directly.

# ── seccomp filters ─────────────────────────────────────────
_BWRAP_SECCOMP_FDS=()
_BWRAP_SECCOMP_TMP_FILES=()
declare -gA _BWRAP_SECCOMP_WARNED_CACHES=()

# Report a seccomp setup problem.
_bwrap_seccomp_fail() {
    echo "bwrap_seccomp: $1" >&2
    return 1
}

# Native architecture for the default blob.
_bwrap_seccomp_arch() {
    printf '%s' "${BWRAP_SECCOMP_ARCH:-$(uname -m)}"
}

# Expected AUDIT_ARCH bytes in the compiled BPF header, in the
# target's native byte order.  tests/arch-table-check.sh compares this table
# with blobs generated by tools/seccomp-gen.*.
_bwrap_seccomp_arch_magic() {
    case "${1:-}" in
        x86_64)               printf '%s' 3e0000c0 ;;
        aarch64)              printf '%s' b70000c0 ;;
        i386|i486|i586|i686)  printf '%s' 03000040 ;;
        armv6l|armv7l|armv8l) printf '%s' 28000040 ;;
        riscv64)              printf '%s' f30000c0 ;;
        ppc64le)              printf '%s' 150000c0 ;;
        ppc64)                printf '%s' 80000015 ;;
        ppc)                  printf '%s' 00000014 ;;
        s390x)                printf '%s' 80000016 ;;
        s390)                 printf '%s' 00000016 ;;
        loongarch64)          printf '%s' 020100c0 ;;
        mips)                 printf '%s' 00000008 ;;
        mipsel)               printf '%s' 08000040 ;;
        mips64)               printf '%s' 80000008 ;;
        mips64el)             printf '%s' 080000c0 ;;
        mips64n32)            printf '%s' a0000008 ;;
        mips64n32el)          printf '%s' 080000e0 ;;
        parisc)               printf '%s' 0000000f ;;
        parisc64)             printf '%s' 8000000f ;;
        *)                    return 1 ;;
    esac
}

# Close filter descriptors inherited by bwrap.
_bwrap_seccomp_close_fds() {
    local _fd
    if (( ${#_BWRAP_SECCOMP_FDS[@]} == 0 )); then
        return 0
    fi
    for _fd in "${_BWRAP_SECCOMP_FDS[@]}"; do
        exec {_fd}<&- 2>/dev/null || true
    done
    _BWRAP_SECCOMP_FDS=()
}

_bwrap_seccomp_tmp_add() {
    _BWRAP_SECCOMP_TMP_FILES+=("$1")
    _bwrap_install_cleanup
}

_bwrap_seccomp_tmp_remove() {
    local _tmp="$1" _keep=() _file
    if (( ${#_BWRAP_SECCOMP_TMP_FILES[@]} == 0 )); then
        return 0
    fi
    for _file in "${_BWRAP_SECCOMP_TMP_FILES[@]}"; do
        [[ "$_file" == "$_tmp" ]] || _keep+=("$_file")
    done
    _BWRAP_SECCOMP_TMP_FILES=("${_keep[@]}")
}

_bwrap_seccomp_tmp_cleanup() {
    local _file
    if (( ${#_BWRAP_SECCOMP_TMP_FILES[@]} == 0 )); then
        return 0
    fi
    for _file in "${_BWRAP_SECCOMP_TMP_FILES[@]}"; do
        rm -f -- "$_file"
    done
    _BWRAP_SECCOMP_TMP_FILES=()
}

# Reject arrays that already contain a seccomp filter.
_bwrap_seccomp_reject_existing() {
    local -n _arr=$1
    local _arg
    for _arg in "${_arr[@]}"; do
        case "$_arg" in
            --seccomp|--add-seccomp-fd)
                echo "bwrap_seccomp: array already contains $_arg" >&2
                return 1
                ;;
        esac
    done
    return 0
}

# Validate FILE and open it as a seccomp filter descriptor.
_bwrap_seccomp_open_fd() {
    local _file="$1"
    local -n _fd_out="$2"
    local _size _arch _want _got _opened_fd

    [[ -f "$_file" && -r "$_file" ]] || {
        _bwrap_seccomp_fail "filter not found or unreadable: $_file"
        return 1
    }

    _size=$(stat -c %s "$_file" 2>/dev/null)
    [[ -n "$_size" ]] || {
        _bwrap_seccomp_fail "cannot stat filter: $_file"
        return 1
    }
    if (( _size <= 0 || _size % 8 != 0 )); then
        _bwrap_seccomp_fail "invalid filter size ($_size): $_file"
        return 1
    fi

    _arch=$(_bwrap_seccomp_arch)
    if ! _want=$(_bwrap_seccomp_arch_magic "$_arch"); then
        _bwrap_seccomp_fail "unsupported architecture: $_arch"
        return 1
    fi
    _got=$(od -An -tx1 -j12 -N4 "$_file" 2>/dev/null | tr -d ' \n')
    if [[ "$_got" != "$_want" ]]; then
        _bwrap_seccomp_fail "filter arch mismatch (want $_want, got ${_got:-none}): $_file"
        return 1
    fi

    if ! exec {_opened_fd}< "$_file"; then
        _bwrap_seccomp_fail "cannot open filter: $_file"
        return 1
    fi
    _BWRAP_SECCOMP_FDS+=("$_opened_fd")
    _bwrap_install_cleanup
    _fd_out="$_opened_fd"
    return 0
}

# Validate FILE, open it and append --seccomp FD to ARRAYNAME.  When
# TEMP is 1 the file is unlinked immediately after it is opened.
_bwrap_seccomp_use() {
    local _arrname="$1" _file="$2" _temp="${3:-0}"
    local -n _arr="$_arrname"

    local _fd
    if ! _bwrap_seccomp_open_fd "$_file" _fd; then
        if [[ "$_temp" == 1 ]]; then
            _bwrap_seccomp_tmp_remove "$_file"
            rm -f -- "$_file"
        fi
        return 1
    fi
    if [[ "$_temp" == 1 ]]; then
        _bwrap_seccomp_tmp_remove "$_file"
        rm -f -- "$_file"
    fi
    _arr+=(--seccomp "$_fd")
    return 0
}

# Path to the default blocklist source.
_bwrap_seccomp_conf() {
    printf '%s' "${BWRAP_SECCOMP_CONF:-${BWRAP_SECCOMP_DIR:-/usr/lib/bwrap-common/seccomp}/default.conf}"
}

# Create/validate the persistent cache directory.
_bwrap_seccomp_cache_ready() {
    local _cache="$1" _real _owner _mode _uid
    _uid=$(id -u) || {
        printf '%s' "cannot determine current uid"
        return 1
    }

    if [[ ! -e "$_cache" ]]; then
        ( umask 077; command mkdir -p "$_cache" 2>/dev/null ) || {
            printf '%s' "cannot create directory"
            return 1
        }
    fi
    [[ -d "$_cache" && -w "$_cache" ]] || {
        printf '%s' "not a writable directory"
        return 1
    }
    _real=$(realpath -e -- "$_cache" 2>/dev/null) || {
        printf '%s' "cannot resolve directory path"
        return 1
    }
    _owner=$(stat -c %u -- "$_real" 2>/dev/null) || {
        printf '%s' "cannot stat directory owner"
        return 1
    }
    if [[ "$_owner" != "$_uid" ]]; then
        printf 'owner uid %s is not current uid %s' "$_owner" "$_uid"
        return 1
    fi
    _mode=$(stat -c %a -- "$_real" 2>/dev/null) || {
        printf '%s' "cannot stat directory mode"
        return 1
    }
    if (( (8#$_mode & 0022) != 0 )); then
        printf 'mode %s is writable by group or others; run chmod go-w %q' \
            "$_mode" "$_cache"
        return 1
    fi
    return 0
}

_bwrap_seccomp_warn_cache() {
    local _cache="${1:-}" _reason="${2:-}"
    if [[ -n "${_BWRAP_SECCOMP_WARNED_CACHES[$_cache]:-}" ]]; then
        return 0
    fi
    _BWRAP_SECCOMP_WARNED_CACHES["$_cache"]=1
    if [[ -n "$_reason" ]]; then
        echo "bwrap_seccomp: seccomp cache unavailable ($_cache): $_reason; using runtime tmpfs fallback" >&2
    else
        echo "bwrap_seccomp: seccomp cache unavailable ($_cache); using runtime tmpfs fallback" >&2
    fi
}

_bwrap_seccomp_conf_path() {
    local _conf
    _conf=$(_bwrap_seccomp_conf)
    [[ -f "$_conf" && -r "$_conf" ]] || {
        _bwrap_seccomp_fail "default seccomp config not found or unreadable: $_conf"
        return 1
    }
    printf '%s' "$_conf"
}

_bwrap_seccomp_gen_version() {
    local _gen="${BWRAP_SECCOMP_GEN:-/usr/lib/bwrap-common/bwrap-seccomp-gen}"
    local _version

    [[ -x "$_gen" ]] || {
        _bwrap_seccomp_fail "seccomp generator not found: $_gen"
        return 1
    }
    _version=$("$_gen" --version 2>/dev/null) || {
        _bwrap_seccomp_fail "cannot query seccomp generator version: $_gen"
        return 1
    }
    [[ -n "$_version" ]] || {
        _bwrap_seccomp_fail "empty seccomp generator version: $_gen"
        return 1
    }
    printf '%s' "$_version"
}

_bwrap_seccomp_cache_valid() {
    local _file="$1" _sum="${1}.sha256" _want _got
    [[ -f "$_file" && -f "$_sum" ]] || return 1
    _want=$(cut -d' ' -f1 "$_sum" 2>/dev/null)
    [[ -n "$_want" ]] || return 1
    _got=$(sha256sum "$_file" 2>/dev/null | cut -d' ' -f1)
    [[ -n "$_got" && "$_got" == "$_want" ]]
}

_bwrap_seccomp_write_sum() {
    local _file="$1" _sum="$2" _hash
    _hash=$(sha256sum "$_file" 2>/dev/null | cut -d' ' -f1)
    [[ -n "$_hash" ]] || return 1
    printf '%s\n' "$_hash" > "$_sum"
}

# Invoke the generator for KIND into OUT.
_bwrap_seccomp_compile() {
    local _kind="$1" _payload="$2" _out="$3"
    local _gen="${BWRAP_SECCOMP_GEN:-/usr/lib/bwrap-common/bwrap-seccomp-gen}"
    local _arch _conf

    if [[ ! -x "$_gen" ]]; then
        _bwrap_seccomp_fail "seccomp generator not found: $_gen"
        return 1
    fi
    _arch=$(_bwrap_seccomp_arch)

    case "$_kind" in
        allowlist)
            "$_gen" --allowlist "$_payload" --arch "$_arch" -o "$_out"
            ;;
        default)
            _conf=$(_bwrap_seccomp_conf_path) || return 1
            "$_gen" --blocklist "$_conf" --arch "$_arch" --strict -o "$_out"
            ;;
        default-extra)
            _conf=$(_bwrap_seccomp_conf_path) || return 1
            "$_gen" --blocklist "$_conf" --extra - --arch "$_arch" --strict \
                -o "$_out" <<< "$_payload"
            ;;
        *)
            _bwrap_seccomp_fail "unknown seccomp filter kind: $_kind"
            return 1
            ;;
    esac
}

# Compile KIND into a temporary file in XDG_RUNTIME_DIR (tmpfs).
_bwrap_seccomp_runtime_prepare() {
    local _kind="$1" _payload="$2"
    local -n _run_path="$3"
    local -n _run_temp="$4"
    local _runtime="${XDG_RUNTIME_DIR:-}"
    local _tmp

    if [[ -z "$_runtime" || ! -d "$_runtime" || ! -w "$_runtime" ]]; then
        _bwrap_seccomp_fail "no writable runtime dir for seccomp fallback: ${_runtime:-<unset>}"
        return 1
    fi
    if ! _tmp=$(mktemp "$_runtime/bwrap-seccomp.XXXXXX" 2>/dev/null); then
        _bwrap_seccomp_fail "cannot create runtime seccomp filter in $_runtime"
        return 1
    fi
    _bwrap_seccomp_tmp_add "$_tmp"
    if ! _bwrap_seccomp_compile "$_kind" "$_payload" "$_tmp"; then
        _bwrap_seccomp_tmp_remove "$_tmp"
        rm -f -- "$_tmp"
        _bwrap_seccomp_fail "failed to compile seccomp filter"
        return 1
    fi
    _run_path="$_tmp"
    _run_temp=1
    return 0
}

# Prepare KIND with cache key HASH, falling back to tmpfs.
_bwrap_seccomp_prepare() {
    local _hash="$1" _kind="$2" _payload="$3"
    local -n _prep_path="$4"
    local -n _prep_temp="$5"
    local _cache _cache_file _tmp

    _cache="${BWRAP_SECCOMP_CACHE_DIR:-${XDG_CACHE_HOME:-$HOME/.cache}/bwrap-common/seccomp}"
    _cache_file="${_cache}/${_hash}.bpf"
    local _cache_ready=0 _cache_reason=""
    if _cache_reason=$(_bwrap_seccomp_cache_ready "$_cache"); then
        _cache_ready=1
    else
        _bwrap_seccomp_warn_cache "$_cache" "$_cache_reason"
    fi

    if (( _cache_ready )) && [[ -f "$_cache_file" ]]; then
        if _bwrap_seccomp_cache_valid "$_cache_file"; then
            _prep_path="$_cache_file"
            _prep_temp=0
            return 0
        fi
        echo "bwrap_seccomp: cached filter failed validation, recompiling: $_cache_file" >&2
    fi

    if (( _cache_ready )); then
        if ! _tmp=$(mktemp "${_cache_file}.tmp.XXXXXX" 2>/dev/null); then
            _bwrap_seccomp_warn_cache "$_cache"
            _bwrap_seccomp_runtime_prepare "$_kind" "$_payload" _prep_path _prep_temp
            return $?
        fi
        _bwrap_seccomp_tmp_add "$_tmp"
        local _sum="${_tmp}.sha256"
        _bwrap_seccomp_tmp_add "$_sum"
        if _bwrap_seccomp_compile "$_kind" "$_payload" "$_tmp"; then
            chmod 600 "$_tmp" 2>/dev/null || true
            if _bwrap_seccomp_write_sum "$_tmp" "$_sum" &&
                mv -f "$_sum" "${_cache_file}.sha256" &&
                mv -f "$_tmp" "$_cache_file"; then
                chmod 600 "$_cache_file" "${_cache_file}.sha256" 2>/dev/null || true
                _bwrap_seccomp_tmp_remove "$_tmp"
                _bwrap_seccomp_tmp_remove "$_sum"
                _prep_path="$_cache_file"
                _prep_temp=0
                return 0
            fi
            rm -f -- "$_tmp" "$_sum"
            _bwrap_seccomp_tmp_remove "$_tmp"
            _bwrap_seccomp_tmp_remove "$_sum"
            _bwrap_seccomp_warn_cache "$_cache"
            _bwrap_seccomp_runtime_prepare "$_kind" "$_payload" _prep_path _prep_temp
            return $?
        fi
        rm -f -- "$_tmp" "$_sum"
        _bwrap_seccomp_tmp_remove "$_tmp"
        _bwrap_seccomp_tmp_remove "$_sum"
        echo "bwrap_seccomp: cached filter compilation failed; retrying in runtime tmpfs" >&2
    fi

    _bwrap_seccomp_runtime_prepare "$_kind" "$_payload" _prep_path _prep_temp
    return $?
}

# Compile the default blocklist, optionally merged with extra rules.
_bwrap_seccomp_default() {
    local _arrname="$1"
    shift
    local _spec="" _rule _kind="default"

    if (( $# > 0 )); then
        for _rule in "$@"; do
            [[ "$_rule" =~ ^[[:space:]]*(#|$) ]] && continue
            [[ -n "$_spec" ]] && _spec+=$'\n'
            _spec+="$_rule"
        done
        if [[ -z "$_spec" ]]; then
            _bwrap_seccomp_fail "empty extra blocklist spec"
            return 1
        fi
        _kind="default-extra"
    fi

    _bwrap_seccomp_reject_existing "$_arrname" || return 1

    if ! command -v sha256sum >/dev/null 2>&1; then
        _bwrap_seccomp_fail "sha256sum not found"
        return 1
    fi

    local _conf _conf_sha _gen_ver _arch _hash
    _conf=$(_bwrap_seccomp_conf_path) || return 1
    _conf_sha=$(sha256sum "$_conf" 2>/dev/null | cut -d' ' -f1)
    if [[ -z "$_conf_sha" ]]; then
        _bwrap_seccomp_fail "failed to hash default seccomp config: $_conf"
        return 1
    fi
    _gen_ver=$(_bwrap_seccomp_gen_version) || return 1

    _arch=$(_bwrap_seccomp_arch)
    if [[ "$_kind" == "default" ]]; then
        _hash=$(printf 'bwrap-common-seccomp-default-v4\n%s\nstrict\n%s\n%s\n' "$_gen_ver" "$_arch" "$_conf_sha" | sha256sum | cut -d' ' -f1)
    else
        _hash=$(printf 'bwrap-common-seccomp-default-extra-v4\n%s\nstrict\n%s\n%s\n%s\n' "$_gen_ver" "$_arch" "$_conf_sha" "$_spec" | sha256sum | cut -d' ' -f1)
    fi
    if [[ -z "$_hash" ]]; then
        _bwrap_seccomp_fail "failed to compute cache key"
        return 1
    fi

    local _path _temp
    _bwrap_seccomp_prepare "$_hash" "$_kind" "$_spec" _path _temp || return 1
    _bwrap_seccomp_use "$_arrname" "$_path" "$_temp"
}

# Compile SPEC to a cached cBPF file, then apply it.
_bwrap_seccomp_allowlist() {
    local _arrname="$1" _spec="$2"

    if ! command -v sha256sum >/dev/null 2>&1; then
        _bwrap_seccomp_fail "sha256sum not found"
        return 1
    fi
    if [[ -z "$_spec" ]]; then
        _bwrap_seccomp_fail "empty allowlist spec"
        return 1
    fi

    _bwrap_seccomp_reject_existing "$_arrname" || return 1

    local _gen_ver _arch _hash
    _gen_ver=$(_bwrap_seccomp_gen_version) || return 1
    _arch=$(_bwrap_seccomp_arch)
    _hash=$(printf 'bwrap-common-seccomp-v4\n%s\nallowlist\n%s\n%s\n' "$_gen_ver" "$_arch" "$_spec" | sha256sum | cut -d' ' -f1)
    if [[ -z "$_hash" ]]; then
        _bwrap_seccomp_fail "failed to compute cache key"
        return 1
    fi

    local _path _temp
    _bwrap_seccomp_prepare "$_hash" allowlist "$_spec" _path _temp || return 1
    _bwrap_seccomp_use "$_arrname" "$_path" "$_temp"
}
